"""Reflex oscillator, Ehlers, TASC February 2020: streaming research master.

SuperSmoother(period=length/2) -> chord-distance average -> EMA mean square
normalization. update(value) returns one scalar Reflex value. Its independent
companion, Trendflex, is prepared in ../trendflex/, not imported by this file.

Use full-precision math.sqrt(2.0) and math.pi as requested by the user.
The original article uses rounded constants; its complete formulas and this
explicit precision substitution are documented in description.md. This master
explicitly defines a fresh finite record: first price establishes Close[1];
no synthetic filtered sample is inserted. Begin the zero-seeded smoother on
the second price. Wait
for length+1 actual smoother values before starting the zero-seeded RMS.
Therefore indexes 0..length return NaN, and length+1 is the first output.
Read description.md for source/history conventions and analytical limits.

Standard Python only. __main__ demonstrates the embedded 252 INPUT_CLOSE
observations. The confirmed reference lengths are generated by running
--generate-reference-data to populate all five copied language fixtures.
"""

from __future__ import annotations

import argparse
import ast
import math
from pathlib import Path
from typing import NamedTuple


# User-requested binary64 mathematical constants, shared by every port.
# Do not restore the printed 1.414 or 3.14159 approximations.
PI = math.pi
SQRT_TWO = math.sqrt(2.0)


class ReflexState(NamedTuple):
    """Read-only diagnostics; unavailable filtered/raw/output values are NaN.

    mean_square stays zero until a complete difference window is available.
    These diagnostics are not extra required fixture outputs; update returns
    the scalar named reflex, as the original indicator's Plot1 does.
    """

    filtered: float
    slope: float
    raw_average: float
    mean_square: float
    reflex: float


class Reflex:
    """Streaming chord-detrended, RMS-normalized oscillator; default length=20.

    length is a positive integer, not a boolean. Length 1 is algebraically
degenerate for Reflex (one zero endpoint distance); use >=2 for meaningful
    analysis. The master still accepts 1 and preserves literal source arithmetic.

    One chronological completed observation per update; finite, float-
    convertible zero and negative inputs are valid. Invalid observations and
    arithmetic overflow are rejected before changing state. No gap filling,
    chart backshifting, future values, or third-party numeric libraries.

    A bounded newest-first list holds length+1 actual filtered observations.
    Two scalar smoother lags and one EMA mean square supply recursive memory.
    Work and storage are O(length). Construct a new instance to change length.
    """

    def __init__(self, length: int = 20) -> None:
        if isinstance(length, bool) or not isinstance(length, int) or length < 1:
            raise ValueError("length must be a positive integer")
        self._length = length
        smoothing_period = 0.5 * length
        # Replace both rounded source constants with the full-precision
        # values explicitly requested by the user. The source cosine angle
        # is in degrees; this is its equivalent full-precision radian form.
        # Use the SAME angle for pole decay and rotation.
        angle = SQRT_TWO * PI / smoothing_period
        self._a1 = math.exp(-angle)
        self._b1 = 2.0 * self._a1 * math.cos(angle)
        self._c2 = self._b1
        self._c3 = -self._a1 * self._a1
        self._c1 = 1.0 - self._c2 - self._c3
        if not 0.0 < self._a1 < 1.0 or not self._c1 > 0.0:
            raise ValueError("length must produce numerically resolvable stable smoother coefficients")
        self.reset()

    @property
    def length(self) -> int:
        """Read-only assumed cycle period and chord/window length in bars."""
        return self._length

    @property
    def warmup_bars(self) -> int:
        """Exactly length+1 public NaNs before the first complete filtered window."""
        return self._length + 1

    @property
    def is_primed(self) -> bool:
        """Complete length+1 filtered observations, not guaranteed IIR settling."""
        return len(self._filtered) == self._length + 1

    @property
    def state(self) -> ReflexState:
        """Latest diagnostics without exposing mutable histories."""
        return self._state

    def reset(self) -> None:
        """Discard the entire stream and restore zero recursive source states."""
        self._previous_price = None
        self._filt1 = 0.0
        self._filt2 = 0.0
        self._filtered = []
        self._ms = 0.0
        self._last_output = 0.0
        self._state = ReflexState(math.nan, math.nan, math.nan, 0.0, math.nan)

    def update(self, value: float) -> float:
        """Consume one finite observation and return Reflex, or history NaN.

        Missing prehistory is not an observation. The first price establishes
        a real previous Close and does not evaluate or fabricate Filt[0].
        Thereafter the original SuperSmoother runs even while the full window
        is collecting. MS starts only at the first complete difference window.
        """
        value = float(value)
        if not math.isfinite(value):
            raise ValueError("input value must be finite")
        if self._previous_price is None:
            self._previous_price = value
            return math.nan

        # Preserve the original multiplication, division, and addition order.
        # c3 is NEGATIVE, so its term is added with that negative coefficient.
        # Check the pair sum separately: finite prices can add to infinity.
        price_pair = value + self._previous_price
        filtered = (self._c1 * price_pair / 2.0
                    + self._c2 * self._filt1 + self._c3 * self._filt2)
        if not math.isfinite(price_pair) or not math.isfinite(filtered):
            raise ValueError("SuperSmoother arithmetic must remain finite")

        # Candidate newest-first history: [0] is current Filt and [length]
        # is the real filtered observation length bars before it. Every entry
        # results from an actual adjacent pair of accepted raw observations.
        history = [filtered] + self._filtered[:self._length]
        slope = math.nan
        raw_average = math.nan
        mean_square = self._ms
        output = math.nan
        stored_output = self._last_output
        if len(history) == self._length + 1:
            # A line (chord) joins the current smoothed value to the value
            # one assumed cycle ago. Lag grows backward, hence this sign.
            slope = (history[self._length] - filtered) / self._length
            total = 0.0  # Reset Sum on EVERY bar, as the source explicitly does.
            for count in range(1, self._length + 1):
                # Source association is `(Sum + line_value) - Filt[count]`.
                # Do NOT replace it with `Sum + (line_value-Filt[count])` or
                # an algebraically collapsed rolling sum for reference data.
                # Old endpoint count=length is included; its ideal residual
                # is zero, but the divisor remains length, not length-1.
                total = total + (filtered + count * slope) - history[count]
            raw_average = total / self._length

            # Fixed EMA of SQUARED RAW AVERAGE, not an EMA of output and not
            # a centered variance. 0.04/0.96 are literal, non-configurable.
            mean_square = 0.04 * raw_average * raw_average + 0.96 * self._ms
            if not all(math.isfinite(v) for v in (slope, raw_average, mean_square)):
                raise ValueError("distance sum and mean square must remain finite")
            # Source guard has no Else: keep the preceding output when MS=0.
            # Starting all-zero input yields zero, rather than 0/0 or NaN.
            if mean_square != 0.0:
                stored_output = raw_average / math.sqrt(mean_square)
            output = stored_output
            if not math.isfinite(output):
                raise ValueError("normalized output must remain finite")

        # Commit the accepted bar together. Availability NaNs never enter
        # the smoother history, mean square, or persistent normalized output.
        self._previous_price = value
        self._filt2 = self._filt1
        self._filt1 = filtered
        self._filtered = history
        self._ms = mean_square
        self._last_output = stored_output
        self._state = ReflexState(filtered, slope, raw_average, mean_square, output)
        return output


